#!/usr/bin/env python3
"""Generate GitHub issue proposals from upstream discovery.

No GitHub writes, notifications, builds, or publication.
"""

import argparse
import json
import re
from pathlib import Path

from discover_upstream import DEFAULT_MANIFEST

REF = re.compile(r"[A-Za-z0-9._+-]{1,100}\Z")


def plan(results):
    if not isinstance(results, list):
        raise ValueError("Expected upstream report list")

    registry = json.loads(
        DEFAULT_MANIFEST.read_text()
    )["packages"]

    proposals = []
    seen = set()

    for item in results:
        if not isinstance(item, dict):
            raise ValueError("Malformed upstream result")

        package = item.get("package")
        if (
            package not in registry
            or registry[package]["status"] != "approved"
        ):
            raise ValueError("Unsupported package")

        if package in seen:
            raise ValueError("Duplicate package in report")
        seen.add(package)

        status = item.get("status")
        if status not in ("update", "unchanged", "blocked"):
            raise ValueError("Unknown candidate status")

        if status != "update":
            continue

        selected = item.get("selected")
        candidate = item.get("candidate")

        if not isinstance(selected, str) or not REF.fullmatch(selected):
            raise ValueError("Invalid selected reference")
        if not isinstance(candidate, str) or not REF.fullmatch(candidate):
            raise ValueError("Invalid candidate reference")

        if candidate == selected:
            raise ValueError("Update has unchanged reference")

        title = f"Package candidate: {package} @ {candidate}"

        body = "\n".join([
            "## Upstream package candidate",
            "",
            "<!-- t4t3z0r:candidate-alert:v1 -->",
            "",
            f"- Package: `{package}`",
            f"- Selected: `{selected}`",
            f"- Candidate: `{candidate}`",
            "",
            "## Review decisions",
            "",
            "- **Approve:** propose selecting this candidate.",
            "- **Deny:** reject this candidate.",
            "- **Postpone:** revisit this candidate later.",
            "- **Pin:** retain the selected source and propose pinning its policy.",
            "",
            "No decision has been recorded.",
            "No builds, signing, or publication are authorized.",
            "",
        ])

        proposals.append({
            "package": package,
            "selected": selected,
            "candidate": candidate,
            "title": title,
            "body": body,
        })

    return proposals


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "report",
        type=Path,
        help="JSON generated by report_upstream.py",
    )
    args = parser.parse_args()

    results = json.loads(args.report.read_text())
    print(json.dumps(plan(results), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
